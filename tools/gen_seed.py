"""Generate supabase/seed.sql (banner + border art) and public/og.png. Stdlib only.

Run from the repo root:  python tools/gen_seed.py
"""
import struct
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
N = 1000

# r/place 2017 palette; index 0 is white. Must match PAL in public/index.html.
PALETTE = [
    "FFFFFF", "E4E4E4", "888888", "222222", "FFA7D1", "E50000", "E59500", "A06A42",
    "E5D900", "94E044", "02BE01", "00D3DD", "0083C7", "0000EA", "CF6EE4", "820080",
]
GREEN, ORANGE, DARK, BLUE = 10, 6, 3, 12

FONT = {  # 5x7
    "S": ["01111", "10000", "10000", "01110", "00001", "00001", "11110"],
    "U": ["10001", "10001", "10001", "10001", "10001", "10001", "01110"],
    "P": ["11110", "10001", "10001", "11110", "10000", "10000", "10000"],
    "A": ["01110", "10001", "10001", "11111", "10001", "10001", "10001"],
    "B": ["11110", "10001", "10001", "11110", "10001", "10001", "11110"],
    "E": ["11111", "10000", "10000", "11110", "10000", "10000", "11111"],
    "X": ["00000", "00000", "10001", "01010", "00100", "01010", "10001"],
    "C": ["01110", "10001", "10000", "10000", "10000", "10001", "01110"],
    "L": ["10000", "10000", "10000", "10000", "10000", "10000", "11111"],
    "D": ["11110", "10001", "10001", "10001", "10001", "10001", "11110"],
    " ": ["00000"] * 7,
}


def rects():
    """Yield (x, y, w, h, colour) rectangles making up the seed art."""
    b = 4  # border thickness
    yield (0, 0, N, b, BLUE)
    yield (0, N - b, N, b, BLUE)
    yield (0, 0, b, N, BLUE)
    yield (N - b, 0, b, N, BLUE)

    text, scale = "SUPABASE X CLAUDE", 6
    colours = [GREEN] * 8 + [DARK] * 3 + [ORANGE] * 6
    adv = 6 * scale
    width = len(text) * adv - scale
    x0, y0 = (N - width) // 2, (N - 7 * scale) // 2
    for i, ch in enumerate(text):
        for row, bits in enumerate(FONT[ch]):
            col = 0
            while col < 5:
                if bits[col] == "1":
                    start = col
                    while col < 5 and bits[col] == "1":
                        col += 1
                    yield (x0 + i * adv + start * scale, y0 + row * scale,
                           (col - start) * scale, scale, colours[i])
                else:
                    col += 1


SEED_HEAD = """-- Seed art: border + centred "SUPABASE x CLAUDE". Generated by tools/gen_seed.py; run after migration.sql.
create or replace function pg_temp.seed_rect(x0 int, y0 int, w int, h int, c int) returns void
language plpgsql as $$
declare vtx int; vty int; d bytea; px int; py int;
begin
  for vty in (y0 / 100)..((y0 + h - 1) / 100) loop
    for vtx in (x0 / 100)..((x0 + w - 1) / 100) loop
      select t.data into d from public.tiles t where t.tx = vtx and t.ty = vty;
      for py in greatest(y0, vty * 100)..least(y0 + h - 1, vty * 100 + 99) loop
        for px in greatest(x0, vtx * 100)..least(x0 + w - 1, vtx * 100 + 99) loop
          d := set_byte(d, (py % 100) * 100 + (px % 100), c);
        end loop;
      end loop;
      update public.tiles t set data = d where t.tx = vtx and t.ty = vty;
    end loop;
  end loop;
end $$;
"""


def write_png(path, w, h, rows, palette):
    def chunk(kind, data):
        body = kind + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body))
    raw = b"".join(b"\x00" + bytes(r) for r in rows)
    png = (b"\x89PNG\r\n\x1a\n"
           + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 3, 0, 0, 0))
           + chunk(b"PLTE", b"".join(bytes.fromhex(c) for c in palette))
           + chunk(b"IDAT", zlib.compress(raw, 9))
           + chunk(b"IEND", b""))
    path.write_bytes(png)


def main():
    all_rects = list(rects())
    sql = SEED_HEAD + "".join(
        f"select pg_temp.seed_rect({x}, {y}, {w}, {h}, {c});\n" for x, y, w, h, c in all_rects)
    (ROOT / "supabase" / "seed.sql").write_text(sql, encoding="utf-8")

    pix = bytearray(N * N)
    for x, y, w, h, c in all_rects:
        for yy in range(y, y + h):
            pix[yy * N + x: yy * N + x + w] = bytes([c]) * w

    # og.png 1200x630: the canvas' centre 1000x630 band on the brand background (#05060d, index 16)
    W, H, top, side = 1200, 630, (N - 630) // 2, 100
    rows = [[16] * side + list(pix[(top + r) * N:(top + r + 1) * N]) + [16] * side for r in range(H)]
    write_png(ROOT / "public" / "og.png", W, H, rows, PALETTE + ["05060D"])
    print(f"{len(all_rects)} rects -> supabase/seed.sql, public/og.png")


if __name__ == "__main__":
    main()
